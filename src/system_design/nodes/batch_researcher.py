class FetchStatus(Enum):
    OK = "ok"            # genuine, usable result content
    EMPTY = "empty"       # source responded fine, no results exist
    BLOCKED = "blocked"   # source is refusing/soft-blocking us
    ERROR = "error"       # transport/parse/unexpected failure

