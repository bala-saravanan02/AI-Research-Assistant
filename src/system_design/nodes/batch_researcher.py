def _flatten_exception(exc: BaseException) -> str:
    """
    Unwraps nested ExceptionGroups generated by anyio/MCP internals
    to surface the actual underlying root cause error message.
    """
    if hasattr(exc, "exceptions"):  # ExceptionGroup (py3.11+)
        return "; ".join(_flatten_exception(sub) for sub in exc.exceptions)
    return f"{type(exc).__name__}: {exc}"


# --- Circuit Breaker States & Config ---
class BreakerState(Enum):
    CLOSED = "closed"        # Tool flows freely
    OPEN = "open"            # All traffic blocked instantly
    HALF_OPEN = "half_open"  # Single test call allowed

class CircuitBreaker:
    def __init__(self):
        self.state = BreakerState.CLOSED
        self.failure_count = 0
        self.failure_threshold = 3
        
        # Cooldown timing settings (in seconds)
        self.base_cooldown = 10.0
        self.current_cooldown = 10.0
        self.next_valid_time = 0.0
        
        # Synchronization lock for state transitions across concurrent tasks
        self.lock = asyncio.Lock()

    async def check_state(self):
        """Evaluates and shifts state dynamically based on timestamps."""
        async with self.lock:
            if self.state == BreakerState.OPEN and time.time() >= self.next_valid_time:
                logger.warning("[Breaker] Cooldown expired. Moving to HALF-OPEN state.")
                self.state = BreakerState.HALF_OPEN
            return self.state

    async def record_success(self):
        """Resets metrics when a test call or normal call succeeds."""
        async with self.lock:
            if self.state == BreakerState.HALF_OPEN:
                logger.info("[Breaker] Test call succeeded! Closing breaker and restoring full traffic.")
                self.current_cooldown = self.base_cooldown  # Reset backoff
            self.state = BreakerState.CLOSED
            self.failure_count = 0

    async def record_failure(self):
        """Increments failures and triggers exponential backoff if threshold is met."""
        async with self.lock:
            self.failure_count += 1
            if self.state == BreakerState.HALF_OPEN or self.failure_count >= self.failure_threshold:
                self.state = BreakerState.OPEN
                self.next_valid_time = time.time() + self.current_cooldown
                logger.critical(
                    f"[Breaker] Failure recorded. Breaker enters OPEN state. "
                    f"Blocking traffic for {self.current_cooldown:.1f} seconds."
                )
                self.current_cooldown *= 2.0

